CREATE SCHEMA IF NOT EXISTS erp_financeiro;

CREATE TABLE IF NOT EXISTS erp_financeiro.contas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nome TEXT NOT NULL UNIQUE,
    saldo NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (saldo >= 0)
);

CREATE TABLE IF NOT EXISTS erp_financeiro.faturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero TEXT NOT NULL UNIQUE,
    conta_id BIGINT NOT NULL REFERENCES erp_financeiro.contas(id),
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    emitida_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO erp_financeiro.contas (id, cliente_nome, saldo)
VALUES (1, 'Cliente Exemplo', 200.00)
ON CONFLICT (id) DO NOTHING;

INSERT INTO erp_financeiro.faturas (numero, conta_id, valor)
VALUES ('FAT-001', 1, 120.00), ('FAT-002', 1, 80.00)
ON CONFLICT (numero) DO NOTHING;

SELECT COUNT(*) AS numero_faturas, SUM(valor) AS total_faturado
FROM erp_financeiro.faturas;
