-- Modelo lógico/físico da loja virtual. Executar em banco de estudo.
CREATE SCHEMA IF NOT EXISTS loja_backend;

CREATE TABLE IF NOT EXISTS loja_backend.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS loja_backend.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    preco NUMERIC(12,2) NOT NULL CHECK (preco >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS loja_backend.estoque (
    produto_id BIGINT PRIMARY KEY REFERENCES loja_backend.produtos(id),
    quantidade INTEGER NOT NULL DEFAULT 0 CHECK (quantidade >= 0)
);

CREATE TABLE IF NOT EXISTS loja_backend.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES loja_backend.clientes(id),
    status VARCHAR(20) NOT NULL DEFAULT 'aberto'
        CHECK (status IN ('aberto', 'confirmado', 'cancelado')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS loja_backend.itens_pedido (
    pedido_id BIGINT NOT NULL REFERENCES loja_backend.pedidos(id),
    produto_id BIGINT NOT NULL REFERENCES loja_backend.produtos(id),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario >= 0),
    PRIMARY KEY (pedido_id, produto_id)
);
